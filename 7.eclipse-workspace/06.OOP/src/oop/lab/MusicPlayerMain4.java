package oop.lab;

public class MusicPlayerMain4 {

	public static void main(String[] args) {
		MusicPlayerDataV2 musicplayer = new MusicPlayerDataV2();
		
		//음악 플레이어 켜기
		musicplayer.On();
		
		//볼륨 증가
		musicplayer.VolUp();
	
		//볼륨 증가
		musicplayer.VolUp();
		
		//볼륨 감소
		musicplayer.VolDown();
	
		//음악 플레이어 상태
		musicplayer.Status();
		
		//음악 플레이어 끄기
		musicplayer.Off();

	}







}
